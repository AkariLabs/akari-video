import { readFile, realpath, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const packageRoot = join(dirname(scriptPath), '..');
const repositoryRoot = join(packageRoot, '../..');
const catalogRoot = join(repositoryRoot, 'presets/textstyle');
const destination = join(packageRoot, 'src/generated/textstyle-catalog.ts');

export async function generateTextstyleCatalogSource(root = catalogRoot) {
  const lines = (await readFile(join(root, 'index.jsonl'), 'utf8'))
    .split(/\r?\n/u)
    .filter(line => line.trim())
    .map(line => JSON.parse(line));
  const entries = [];
  const ids = new Set();
  for (const indexEntry of lines) {
    if (typeof indexEntry.id !== 'string' || ids.has(indexEntry.id)) {
      throw new Error(`textstyle index has an invalid or duplicate id: ${String(indexEntry.id)}`);
    }
    ids.add(indexEntry.id);
    const preset = JSON.parse(await readFile(join(root, `${indexEntry.id}.json`), 'utf8'));
    if (preset.id !== indexEntry.id) {
      throw new Error(`textstyle id mismatch: ${indexEntry.id}`);
    }
    entries.push([indexEntry.id, {
      id: indexEntry.id,
      name: preset.name,
      category: preset.category,
      style: preset.style,
    }]);
  }
  entries.sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0);
  const catalog = Object.fromEntries(entries);
  return [
    '// Generated by scripts/gen-textstyle-catalog.mjs from presets/textstyle.',
    '// Do not edit by hand.',
    '',
    "import type { TextstylePreset } from '../caption-style-preset';",
    '',
    `export const TEXTSTYLE_CATALOG: Record<string, TextstylePreset> = ${JSON.stringify(catalog, null, 2)};`,
    '',
  ].join('\n');
}

async function isMain() {
  if (!process.argv[1]) return false;
  try {
    return await realpath(process.argv[1]) === await realpath(scriptPath);
  } catch {
    return false;
  }
}

if (await isMain()) {
  await writeFile(destination, await generateTextstyleCatalogSource(), 'utf8');
}
