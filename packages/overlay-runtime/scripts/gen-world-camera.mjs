import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(packageRoot, "../akari-tools/src/world/camera.mjs");
const outputPath = resolve(packageRoot, "src/vendor/world-camera.js");

const source = await readFile(sourcePath, "utf8");
const body = source.replace(/^export\s+/gmu, "").trimEnd();
const generated = `// Generated by scripts/gen-world-camera.mjs from akari-tools/src/world/camera.mjs.\n(function(){\n${body}\nwindow.AkariWorldCamera = { createCamera };\n})();\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => null);
  if (current !== generated) {
    console.error("src/vendor/world-camera.js is out of date; run npm run gen:world-camera");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
