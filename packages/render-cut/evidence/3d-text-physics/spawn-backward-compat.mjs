// 後方互換 evidence（task 2026-08-14-3d-physics-spawn の受け入れ条件）。physics.spawn 未宣言時の
// 挙動が three-runtime.js の spawn 対応（physicsInitialState への spawn 引数追加）で 1 ピクセルも
// 変わっていないことを確認する。
//
// determinism-seek.mjs を再実行して artifacts/determinism-seek-result.json を上書きするのではなく
// （既存証跡を破壊しないため）、同じ basicFallScene（spawn 未宣言）を本タスクの three-runtime.js
// 変更後に独立で 1 回書き出し、本タスク着手前に記録済みの determinism-seek-result.json の
// run1Hashes（24 frame, SHA-256）と完全一致するかを新規 artifact へ書く。
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { captureWithPuppeteer, renderOverlaySheet } from "../../src/rasterize.mjs";
import {
  editFor,
  loadPuppeteerModule,
  makeProjectRoot,
  overlayFor,
  resolveChromePath,
  sha256File,
} from "./shared/fixtures.mjs";
import { basicFallScene } from "./shared/scenes.mjs";

const ARTIFACTS_DIR = join(new URL(".", import.meta.url).pathname, "artifacts");
const RECORDED_PATH = join(ARTIFACTS_DIR, "determinism-seek-result.json");

const edit = editFor({ width: 480, height: 270, fps: 10 });
const DURATION = 2.4; // 24 frames @ 10fps — determinism-seek.mjs と同一パラメータ

async function runOnce(label) {
  const projectRoot = await makeProjectRoot(`spawn-backward-compat-${label}`);
  try {
    const workDir = join(projectRoot, "work");
    await mkdir(workDir, { recursive: true });
    // spawn を渡さない = physics.spawn 未宣言。basicFallScene は本タスク前から変更していない
    const overlay = overlayFor("phys", basicFallScene({ duration: DURATION }), { start: 0, duration: DURATION });
    const sheetPath = join(workDir, "sheet.html");
    await writeFile(
      sheetPath,
      renderOverlaySheet({ overlays: [overlay], edit, projectRoot, duration: DURATION }),
      "utf8",
    );
    const puppeteerModule = await loadPuppeteerModule();
    const chromePath = await resolveChromePath();
    const framesDirectory = join(workDir, "frames");
    await captureWithPuppeteer({
      sheetPath,
      chromePath,
      framesDirectory,
      overlayMovPath: join(workDir, "overlay.mov"),
      width: edit.output.width,
      height: edit.output.height,
      fps: edit.output.fps,
      duration: DURATION,
      ffmpegCommand: "ffmpeg",
      puppeteerModule,
    });
    const frameFiles = (await readdir(framesDirectory)).filter((f) => f.endsWith(".png")).sort();
    const hashes = [];
    for (const file of frameFiles) hashes.push(await sha256File(join(framesDirectory, file)));
    return { frameCount: frameFiles.length, hashes };
  } finally {
    await rm(projectRoot, { recursive: true, force: true });
  }
}

const recorded = JSON.parse(await readFile(RECORDED_PATH, "utf8"));
const recordedHashes = recorded.determinism.run1Hashes;

const fresh = await runOnce("fresh");

const allFramesMatch = fresh.frameCount === recordedHashes.length
  && fresh.hashes.every((hash, index) => hash === recordedHashes[index]);

const result = {
  generated_at_note: "generated by evidence/3d-text-physics/spawn-backward-compat.mjs",
  note:
    "physics.spawn 未宣言の basicFallScene を task 2026-08-14-3d-physics-spawn の three-runtime.js "
    + "変更後に再実行し、本タスク着手前に記録済みの determinism-seek-result.json の run1Hashes "
    + "（24 frame, SHA-256）と完全一致することを確認する（後方互換。1 ピクセルでも変わったら FAIL）。",
  scene: "basicFallScene (physics, spawn undeclared, id=phys, floor+wall*2+circle, アカリビデオ物理)",
  recordedFrom: "artifacts/determinism-seek-result.json (determinism.run1Hashes)",
  output: edit.output,
  duration_seconds: DURATION,
  frameCount: fresh.frameCount,
  recordedFrameCount: recordedHashes.length,
  freshHashes: fresh.hashes,
  recordedHashes,
  allFramesMatch,
};

await mkdir(ARTIFACTS_DIR, { recursive: true });
await writeFile(
  join(ARTIFACTS_DIR, "spawn-backward-compat-result.json"),
  JSON.stringify(result, null, 2),
  "utf8",
);
console.log(JSON.stringify({ frameCount: result.frameCount, allFramesMatch }, null, 2));
if (!allFramesMatch) process.exitCode = 1;
