// 狙い smoke（task 2026-08-14-3d-physics-spawn の受け入れ条件）。狭い spawn（x ±0.5）を細い
// flat-top platform collider（x∈[-0.7,0.7]）の直上へ宣言し（shared/scenes.mjs spawnAimScene）、
// settle で collider 上に文字が乗ることを 1 フレームで確認する。旧 5 レーン固定グリッド
// （laneCount=5, x=(col-2)*1.1+jitter）では列 0/4 が x=±2.2 固定のため、この幅の collider には
// 最初から乗せられない（社内実測: 頭幅 ±0.9 の帯へ seed を 242 通り全数探索しても 1 文字も
// 乗らなかった）。floor はさらに下（y=-5.0）に安全網として置いてあるため、狙いが外れれば
// 「collider から離れた位置で静止する／floor 付近まで落ちる」で判別できる。
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { renderOverlaySheet } from "../../src/rasterize.mjs";
import {
  compositeOverBackground,
  editFor,
  launchBrowser,
  makeProjectRoot,
  overlayFor,
} from "./shared/fixtures.mjs";
import { spawnAimScene } from "./shared/scenes.mjs";

const ARTIFACTS_DIR = join(new URL(".", import.meta.url).pathname, "artifacts");
await mkdir(ARTIFACTS_DIR, { recursive: true });

const edit = editFor({ width: 480, height: 480, fps: 10 });
const DURATION = 3.0;
const SPAWN = { x: [-0.5, 0.5], y: [1.0, 1.6] };
// shared/scenes.mjs SPAWN_TARGET_PLATFORM_POINTS の flat top（x∈[-0.7,0.7], top y=-0.5）と一致させる
const PLATFORM = { xMin: -0.7, xMax: 0.7, topY: -0.5 };
const FLOOR_Y = -5.0;
// 2 時刻間の位置移動量がこの世界単位未満なら「静止（settle 済み）」とみなす
const SETTLE_EPSILON = 0.01;
// 文字の概略半サイズぶんの余裕
const CHAR_MARGIN = 0.25;

function isOnPlatform(x, y) {
  return x >= PLATFORM.xMin - CHAR_MARGIN
    && x <= PLATFORM.xMax + CHAR_MARGIN
    && y > PLATFORM.topY - CHAR_MARGIN * 2
    && y > FLOOR_Y + 1.0;
}

const projectRoot = await makeProjectRoot("spawn-aim-smoke");
try {
  const workDir = join(projectRoot, "work");
  await mkdir(workDir, { recursive: true });
  const scene = spawnAimScene({ duration: DURATION });
  const overlay = overlayFor("phys", scene, { start: 0, duration: DURATION });
  const sheetPath = join(workDir, "sheet.html");
  await writeFile(
    sheetPath,
    renderOverlaySheet({ overlays: [overlay], edit, projectRoot, duration: DURATION }),
    "utf8",
  );

  const { browser } = await launchBrowser();
  let earlierStates;
  let settleStates;
  const settleFramePath = join(ARTIFACTS_DIR, "spawn-aim-smoke-settled.png");
  const settleViewablePath = join(ARTIFACTS_DIR, "spawn-aim-smoke-settled-viewable.png");
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: edit.output.width, height: edit.output.height, deviceScaleFactor: 1 });
    await page.goto(pathToFileURL(sheetPath).href, { waitUntil: "networkidle0", timeout: 60000 });
    await page.evaluate(() => window.__akariReady);

    async function charStatesAt(seconds) {
      await page.evaluate((t) => window.__akariSeek(t), seconds);
      return page.evaluate(() => {
        const container = document.querySelector(".akari-overlay-container > .scene-content");
        return window.akari.threeRuntime.inspect(container).physics.charStates;
      });
    }

    // DURATION ちょうどは overlay の可視区間 [start, start+duration) の外
    const earlierSeconds = DURATION - 0.2;
    const settleSeconds = DURATION - 0.1;
    earlierStates = await charStatesAt(earlierSeconds);
    settleStates = await charStatesAt(settleSeconds);
    await page.screenshot({ path: settleFramePath, omitBackground: true });
  } finally {
    await browser.close();
  }

  compositeOverBackground(settleFramePath, settleViewablePath);

  const perChar = settleStates.map((state, index) => {
    const earlier = earlierStates[index];
    const displacement = Math.hypot(state.x - earlier.x, state.y - earlier.y);
    return {
      index,
      x: state.x,
      y: state.y,
      displacement,
      settled: displacement < SETTLE_EPSILON,
      onCollider: isOnPlatform(state.x, state.y),
    };
  });

  const onColliderCount = perChar.filter((c) => c.onCollider).length;
  const settledCount = perChar.filter((c) => c.settled).length;

  const result = {
    generated_at_note: "generated by evidence/3d-text-physics/spawn-aim-smoke.mjs",
    scene: "spawnAimScene (physics.spawn x∈[-0.5,0.5] y∈[1.0,1.6] above a flat-top platform collider x∈[-0.7,0.7], far floor as safety net)",
    spawn: SPAWN,
    platform: PLATFORM,
    floorY: FLOOR_Y,
    duration_seconds: DURATION,
    settleSeconds: DURATION - 0.1,
    charCount: settleStates.length,
    perChar,
    onColliderCount,
    settledCount,
    frame: "artifacts/spawn-aim-smoke-settled-viewable.png",
    pass: perChar.length > 0 && perChar.every((c) => c.onCollider && c.settled),
  };

  await writeFile(
    join(ARTIFACTS_DIR, "spawn-aim-smoke-result.json"),
    JSON.stringify(result, null, 2),
    "utf8",
  );
  console.log(JSON.stringify(
    { charCount: result.charCount, onColliderCount, settledCount, pass: result.pass },
    null,
    2,
  ));
  if (!result.pass) process.exitCode = 1;
} finally {
  await rm(projectRoot, { recursive: true, force: true });
}
