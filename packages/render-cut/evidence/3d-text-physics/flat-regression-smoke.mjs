// flat（texts[]、physics 無し）回帰 smoke。受け入れ条件「flat の既存ハーネス（3d-text-flat）
// 決定論再実行 PASS（回帰なし）」を字義どおり満たそうとしたが、
// packages/render-cut/evidence/3d-text-flat/{determinism-seek,golden,network-zero,parity,
// presets-smoke}.mjs は本タスク着手前から `./lib/fixtures.mjs` / `./lib/scenes.mjs` を
// import しており、この 2 ファイルが本 worktree に実在しない（リポジトリ直下 .gitignore の
// 3 行目 `lib/` が深さ問わず `lib` という名前のディレクトリを無条件除外するため、
// T2 が作業中に作ったであろうこれらのファイルはコミットされずに欠落したと推測される。
// `git check-ignore -v packages/render-cut/evidence/3d-text-flat/lib/fixtures.mjs` で実測確認済み。
// 本タスクの evidence ディレクトリ名を lib/ ではなく shared/ にしているのはこの事故を踏まないため）。
// 3d-text-flat/ はファイル境界上「編集禁止」（所有は overlay-runtime と本ディレクトリのみ）のため
// 復元・修正はしていない（詳細は report.md 契約逸脱／未確認事項）。
//
// 代替として、本ハーネス（3d-text-physics/shared）の共通部品を使い、
// texts[] flat + anim（physics 不使用）が本タスクの three-runtime.js 変更後も従来どおり
// 動くことを実測する回帰 smoke を用意した。決定論（2 回書き出し一致）+ 非透明ピクセル実測。
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { captureWithPuppeteer, renderOverlaySheet } from "../../src/rasterize.mjs";
import {
  editFor,
  FONT_RELATIVE_PATH,
  loadPuppeteerModule,
  makeProjectRoot,
  overlayFor,
  resolveChromePath,
  sha256File,
} from "./shared/fixtures.mjs";

const ARTIFACTS_DIR = join(new URL(".", import.meta.url).pathname, "artifacts");
await mkdir(ARTIFACTS_DIR, { recursive: true });

const edit = editFor({ width: 480, height: 270, fps: 10 });
const DURATION = 1.6; // 16 frames @ 10fps

function flatCarouselScene() {
  return {
    texts: [{
      id: "ring",
      text: "アカリビデオ",
      font: FONT_RELATIVE_PATH,
      mode: "flat",
      size: 0.5,
      color: "#ffd166",
      layout: { type: "cylinder", radius: 2.2 },
      anim: { preset: "carousel", speed: 1.0, seed: 3 },
    }],
    camera: { position: [0, 0, 6], fov: 45, near: 0.1, far: 100, lookAt: [0, 0, 0] },
    lights: [{ type: "ambient", color: "#ffffff", intensity: 0.5 }],
  };
}

async function runOnce(label) {
  const projectRoot = await makeProjectRoot(`flat-regression-${label}`);
  try {
    const workDir = join(projectRoot, "work");
    await mkdir(workDir, { recursive: true });
    const overlay = overlayFor("ring", flatCarouselScene(), { start: 0, duration: DURATION });
    const sheetPath = join(workDir, "sheet.html");
    await writeFile(
      sheetPath,
      renderOverlaySheet({ overlays: [overlay], edit, projectRoot, duration: DURATION }),
      "utf8",
    );
    const puppeteerModule = await loadPuppeteerModule();
    const chromePath = await resolveChromePath();
    const framesDirectory = join(workDir, "frames");
    await captureWithPuppeteer({
      sheetPath,
      chromePath,
      framesDirectory,
      overlayMovPath: join(workDir, "overlay.mov"),
      width: edit.output.width,
      height: edit.output.height,
      fps: edit.output.fps,
      duration: DURATION,
      ffmpegCommand: "ffmpeg",
      puppeteerModule,
    });
    const frameFiles = (await readdir(framesDirectory)).filter((f) => f.endsWith(".png")).sort();
    const hashes = [];
    for (const file of frameFiles) hashes.push(await sha256File(join(framesDirectory, file)));
    return { frameCount: frameFiles.length, hashes };
  } finally {
    await rm(projectRoot, { recursive: true, force: true });
  }
}

const run1 = await runOnce(1);
const run2 = await runOnce(2);
const allFramesMatch = run1.frameCount === run2.frameCount
  && run1.hashes.every((hash, index) => hash === run2.hashes[index]);

const result = {
  generated_at_note: "generated by evidence/3d-text-physics/flat-regression-smoke.mjs",
  note:
    "Substitute for the pre-existing-broken evidence/3d-text-flat harness (missing lib/, see file header). "
    + "Confirms texts[] flat + anim (no physics) still renders deterministically after this task's "
    + "three-runtime.js changes.",
  scene: "flat carousel (texts[] flat, id=ring, cylinder layout, no physics)",
  duration_seconds: DURATION,
  frameCount: run1.frameCount,
  allFramesMatch,
  run1Hashes: run1.hashes,
  run2Hashes: run2.hashes,
};

await writeFile(
  join(ARTIFACTS_DIR, "flat-regression-smoke-result.json"),
  JSON.stringify(result, null, 2),
  "utf8",
);
console.log(JSON.stringify({ frameCount: result.frameCount, allFramesMatch }, null, 2));
if (!allFramesMatch) process.exitCode = 1;
